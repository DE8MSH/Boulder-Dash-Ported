#!/usr/bin/env python3
from pathlib import Path
import argparse

COLS = 40
ROWS = 22

# The original game draws one logical cave object as a 2x2 block of C64
# characters. At the current 256x224 console resolution that gives a natural
# 16x14 logical-object viewport -> 32x28 hardware character cells.
VIEW_OBJ_W = 16
VIEW_OBJ_H = 14
CHAR_VIEW_W = VIEW_OBJ_W * 2
CHAR_VIEW_H = VIEW_OBJ_H * 2

T_EMPTY = 0x00
T_SOIL = 0x01
T_WALL_STONE = 0x02
T_WALL_STEEL = 0x07
T_BOULDER = 0x10
T_DIAMOND = 0x14
T_BIRTH = 0x25

# Original Boulder Dash I TabCaveTileCharNo mapping from BoulderDashI.asm.
TILE_TO_CHAR = (
    0x60, 0x46, 0x4E, 0x22, 0x2E, 0x62, 0x2E, 0x4A,
    0x64, 0x64, 0x64, 0x64, 0x64, 0x64, 0x64, 0x64,
    0x44, 0x44, 0x44, 0x44, 0x48, 0x48, 0x48, 0x48,
    0x00, 0x00, 0x00, 0x66, 0x68, 0x6A, 0x68, 0x66,
    0x24, 0x26, 0x28, 0x2A, 0x2C, 0x62, 0x66, 0x68,
    0x6A, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x20, 0x20, 0x20, 0x20, 0x20, 0x20, 0x20, 0x20,
    0x4C, 0x4C, 0x40, 0x40, 0x00, 0x00, 0x00, 0x00,
)

SEED = 0x0A
START = 0x00
RND_OBJECTS = (T_EMPTY, T_BOULDER, T_DIAMOND, T_EMPTY)
RND_PROBS = (0x3C, 0x32, 0x09, 0x00)


def rnd_step(seed: int, start: int):
    # Exact 8-bit behavior of GetValPseudoRND in BoulderDashI.asm.
    p1 = 0x80 if (start & 0x02) else 0x00
    p2 = (seed >> 1) & 0x7F
    seed_sum = seed + (0x80 if (seed & 0x01) else 0x00) + 0x13
    carry = 1 if seed_sum > 0xFF else 0
    seed = seed_sum & 0xFF
    start = (start + p1 + p2 + carry) & 0xFF
    return seed, start, start


def build_full_cave():
    cave = [[T_EMPTY for _ in range(COLS)] for _ in range(ROWS)]
    seed = SEED
    start = START

    # Original code advances the RNG across all 40 columns for rows 1..21.
    for row in range(1, ROWS):
        for col in range(COLS):
            seed, start, value = rnd_step(seed, start)
            tile = T_SOIL
            for obj, prob in zip(RND_OBJECTS, RND_PROBS):
                if value < prob:
                    tile = obj
            cave[row][col] = tile

    # CaveFrame steel boundary around the real 40x22 cave.
    for col in range(COLS):
        cave[0][col] = T_WALL_STEEL
        cave[ROWS - 1][col] = T_WALL_STEEL
    for row in range(ROWS):
        cave[row][0] = T_WALL_STEEL
        cave[row][COLS - 1] = T_WALL_STEEL

    # Cave 1 variable commands from B1_CaveData.asm.
    for col in range(1, 31):
        cave[9][col] = T_WALL_STONE
    for col in range(9, 39):
        cave[16][col] = T_WALL_STONE
    cave[4][3] = T_BIRTH
    return cave


def build_char_view(cave):
    """Expand 16x14 logical objects to the exact original 2x2 char layout."""
    chars = [[0 for _ in range(CHAR_VIEW_W)] for _ in range(CHAR_VIEW_H)]
    for obj_y in range(VIEW_OBJ_H):
        for obj_x in range(VIEW_OBJ_W):
            base = TILE_TO_CHAR[cave[obj_y][obj_x]]
            char_y = obj_y * 2
            char_x = obj_x * 2
            chars[char_y][char_x] = base
            chars[char_y][char_x + 1] = (base + 0x01) & 0xFF
            chars[char_y + 1][char_x] = (base + 0x10) & 0xFF
            chars[char_y + 1][char_x + 1] = (base + 0x11) & 0xFF
    return chars


def emit_common(path: Path, chars):
    lines = [
        '; generated by scripts/generate-cave1.py',
        '; 32x28 C64 character-index viewport made from 16x14 logical cave objects.',
        '; Each logical object is the original base, base+1, base+$10, base+$11.',
        f'game_cave_view_width = {CHAR_VIEW_W}',
        f'game_cave_view_height = {CHAR_VIEW_H}',
        '',
        'game_cave_view:',
    ]
    for row in chars:
        values = ', '.join(f'${value:02x}' for value in row)
        lines.append(f'    .byte {values}')
    lines.append('')
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('\n'.join(lines), encoding='utf-8')


def emit_pce(path: Path, chars):
    lines = [
        '; generated by scripts/generate-cave1.py',
        '; HuC6270 BAT words for the same 32x28 expanded C64 character viewport.',
        'pce_cave_bat:',
    ]
    for row in chars:
        values = ', '.join(f'(PCE_PATTERN_TILE + ${value:02x})' for value in row)
        lines.append(f'    .word {values}')
    lines += ['', f'pce_cave_bat_bytes = {CHAR_VIEW_W} * {CHAR_VIEW_H} * 2', '']
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('\n'.join(lines), encoding='utf-8')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('common_output', type=Path)
    parser.add_argument('pce_output', type=Path)
    args = parser.parse_args()

    cave = build_full_cave()
    chars = build_char_view(cave)
    emit_common(args.common_output, chars)
    emit_pce(args.pce_output, chars)
    print(f'generated {args.common_output}')
    print(f'generated {args.pce_output}')


if __name__ == '__main__':
    main()
